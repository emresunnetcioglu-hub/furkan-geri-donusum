-- Run in Supabase SQL Editor. Create administrator user via Supabase Auth dashboard.
create table if not exists public.products (
 id bigint generated by default as identity primary key,
 name text not null, category text not null, description text not null default '',
 price numeric(12,2) not null default 0 check (price >= 0),
 unit text not null default 'kg', emoji text not null default '♻️',
 updated_at timestamptz not null default now()
);
create table if not exists public.price_suggestions (
 id bigint generated by default as identity primary key,
 product_id bigint not null references public.products(id) on delete cascade,
 proposed_price numeric(12,2) not null check (proposed_price >= 0),
 source text not null, source_url text,
 observed_at timestamptz not null default now(),
 status text not null default 'pending' check(status in ('pending','approved','rejected')),
 reviewed_at timestamptz
);
create table if not exists public.admin_users (user_id uuid primary key references auth.users(id) on delete cascade);
create table if not exists public.site_settings (key text primary key, value text not null default '');
insert into public.site_settings(key,value) values ('whatsapp','') on conflict do nothing;
alter table public.products enable row level security;
alter table public.price_suggestions enable row level security;
alter table public.admin_users enable row level security;
alter table public.site_settings enable row level security;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path = public as $$
 select exists(select 1 from public.admin_users where user_id = (select auth.uid()));
$$;
create policy "Products public read" on public.products for select to anon,authenticated using (true);
create policy "Products admin insert" on public.products for insert to authenticated with check (public.is_admin());
create policy "Products admin update" on public.products for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Products admin delete" on public.products for delete to authenticated using (public.is_admin());
create policy "Suggestions admin read" on public.price_suggestions for select to authenticated using (public.is_admin());
create policy "Suggestions admin insert" on public.price_suggestions for insert to authenticated with check (public.is_admin());
create policy "Suggestions admin update" on public.price_suggestions for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Admin membership self read" on public.admin_users for select to authenticated using (user_id=(select auth.uid()));
create policy "Settings public read" on public.site_settings for select to anon,authenticated using (true);
create policy "Settings admin update" on public.site_settings for update to authenticated using (public.is_admin()) with check (public.is_admin());
create or replace function public.review_price_suggestion(p_id bigint,p_approve boolean)
returns void language plpgsql security definer set search_path=public as $$
declare v public.price_suggestions%rowtype;
begin
 if not public.is_admin() then raise exception 'Unauthorized'; end if;
 select * into v from public.price_suggestions where id=p_id for update;
 if not found or v.status <> 'pending' then raise exception 'Suggestion not pending'; end if;
 if p_approve then
  update public.products set price=v.proposed_price,updated_at=now() where id=v.product_id;
 end if;
 update public.price_suggestions set status=case when p_approve then 'approved' else 'rejected' end,reviewed_at=now() where id=p_id;
end;$$;
revoke all on function public.review_price_suggestion(bigint,boolean) from public;
grant execute on function public.review_price_suggestion(bigint,boolean) to authenticated;
